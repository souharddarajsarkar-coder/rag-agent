CODE_BLOCK = re.compile(r"```[ \t]*([\w+-]*)[ \t]*\r?\n(.*?)(?:```|\Z)", re.DOTALL)
GUI_CALL = re.compile(r"(?<![\w.])(?:cv2?\.(?:imshow|waitKey|namedWindow)|plt\.show|input)\s*\(")
UNREADABLE_INPUT = re.compile(r"can't open/read file")


def code_only(code: str) -> str:
    """The script with comments and string literals blanked out, so that
    '# do not call cv2.imshow()' or print("no input() here") are not mistaken for calls."""
    import io
    import tokenize
    try:
        out = []
        for tok in tokenize.generate_tokens(io.StringIO(code).readline):
            if tok.type in (tokenize.COMMENT, tokenize.STRING) or tok.type == getattr(tokenize, "FSTRING_MIDDLE", -1):
                continue
            out.append(tok.string)
        return " ".join(out).replace(" . ", ".").replace(" (", "(")
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return "\n".join(line.split("#", 1)[0] for line in code.splitlines())


def extract_code(reply: str) -> str:
    blocks = [body for language, body in CODE_BLOCK.findall(reply)
              if language.lower() in ("", "python", "python3", "py")]
    if blocks:
        return max(blocks, key=len).strip() + "\n"
    if "```" not in reply and re.search(r"^\s*(import|from)\s+\w+", reply, re.MULTILINE):
        return reply.strip() + "\n"
    return ""


@dataclass
class RunResult:
    returncode: int | None    # None when the script was killed by the timeout
    stdout: str
    stderr: str
    seconds: float


def run_script(script: Path, workdir: Path, timeout: int) -> RunResult:
    env = dict(os.environ, PYTHONIOENCODING="utf-8", MPLBACKEND="Agg")
    start = time.time()
    try:
        p = subprocess.run([sys.executable, str(script)], cwd=str(workdir), env=env,
                           stdin=subprocess.DEVNULL, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=timeout)
        return RunResult(p.returncode, p.stdout, p.stderr, time.time() - start)
    except subprocess.TimeoutExpired as exc:
        def text(data):
            return data.decode("utf-8", "replace") if isinstance(data, bytes) else (data or "")
        return RunResult(None, text(exc.stdout), text(exc.stderr), time.time() - start)


def tail(text: str, limit: int = MAX_ERROR_CHARS) -> str:
    text = text.strip()
    return text if len(text) <= limit else "... " + text[-limit:]


def find_failure(result: RunResult, timeout: int) -> str | None:
    output = f"--- stderr ---\n{tail(result.stderr) or '(empty)'}"
    if result.stdout.strip():
        output += f"\n--- stdout (end) ---\n{tail(result.stdout, 600)}"
    if result.returncode is None:
        return (f"TIMEOUT: the script was killed after {timeout} seconds without finishing. "
                "Typical causes: waiting for a window, key press or webcam, or an endless loop.\n" + output)
    if result.returncode != 0:
        return f"The script crashed with exit code {result.returncode}.\n{output}"
    if UNREADABLE_INPUT.search(result.stderr):
        return ("The script exited with code 0, but OpenCV reported that an input file could not "
                "be read, so the task was not actually carried out.\n" + output)
    return None


def exception_line(error: str) -> str:
    for line in reversed(error.split("--- stdout", 1)[0].splitlines()):
        line = line.strip()
        if re.match(r"[\w.]*(Error|Exception|Interrupt)\b", line) or line.startswith("cv2.error"):
            return line
    return ""


def similar_names(owner: str, attr: str) -> list[str]:
    """Existing members of a module / class spelled like `attr` (checked live with dir())."""
    alias = {"np": "numpy", "cv": "cv2"}
    parts = owner.split(".")
    try:
        obj = importlib.import_module(alias.get(parts[0], parts[0]))
        for p in parts[1:]:
            obj = getattr(obj, p)
    except Exception:
        return []
    return [f"{owner}.{m}" for m in difflib.get_close_matches(attr, dir(obj), n=5, cutoff=0.6)]


def analyse_error(error: str, files: list[str]):
    """API names involved in an error + hints for the LLM."""
    names = re.findall(r"\b(?:cv2|np|numpy|sklearn|torch)\.[A-Za-z_][\w.]*\w", error)
    names += re.findall(r"in function '(?:cv::)?([\w:]+)'", error)
    hints = []
    for owner, attr in re.findall(r"'([\w.]+)'(?: object)? has no attribute '(\w+)'", error):
        similar = similar_names(owner, attr)
        hints.append(f"- `{owner}.{attr}` does NOT exist in the installed version."
                     + (f" Similar names that do exist: {', '.join(similar)}." if similar
                        else " Solve the task with a different API."))
        names = [attr] + [s.rsplit(".", 1)[-1] for s in similar] + names
    if re.search(r"NoneType|\.empty\(\)|FileNotFoundError|No such file|can't open/read", error):
        hints.append("- An input was not loaded (cv2.imread returns None when it cannot read a file). "
                     f"Files that exist in the working directory: {', '.join(files) or 'none'}. "
                     "Use one of those, or build a synthetic image if the task names no file.")
    return list(dict.fromkeys(names)), hints


def library_versions() -> str:
    from importlib import metadata
    found = []
    for module, package in LIBRARIES.items():
        try:
            found.append(f"{module} {metadata.version(package)}")
        except Exception:
            if module == "cv2":
                for alt in ("opencv-contrib-python", "opencv-python-headless", "opencv-contrib-python-headless"):
                    try:
                        found.append(f"cv2 {metadata.version(alt)}")
                        break
                    except Exception:
                        pass
    return ", ".join(found) or "numpy, opencv"


