"""
rag_agent.py - offline RAG + VLM + self-correcting code agent for Computer Vision tasks.

The documentation is NOT generated by this script: it is read from the
documentation folder that sits next to it (default: ./Documentation).

Two modes:  CODE (default) writes and runs a script;  --answer explains in text.

One run of the agent (CODE mode):

    task (natural language)
        |
    0. INDEX     read every file in the documentation folder (PDF, HTML, TXT, MD ...),
                 cut it into chunks and store them in a persistent ChromaDB collection
                 (./chroma_db).  This happens once; later runs reuse the database
                 until the folder changes.
    1. LOOK      (VLM) a vision-language model (llava, qwen-vl, moondream, gemma ...)
                 describes the input image(s), so the coder knows what is in them.
    2. RETRIEVE  the documentation chunks relevant to the task: ChromaDB vector search
                 + BM25 keyword search, merged.
    3. GENERATE  a Python script with the offline coder LLM (Ollama).
    4. EXECUTE   the script in a subprocess and capture stdout / stderr / exit code.
    5. CORRECT   if it crashed, send the error + documentation retrieved for the
                 error back to the LLM, then go to 4.
    6. VERIFY    (VLM) when the script runs, the vision model looks at the output
                 image(s) and judges whether they really solve the task.  A "NO" is
                 fed back to the coder like an error (limited by --vlm-retries).

LangChain is used for the RAG pipeline when it is installed:
    RecursiveCharacterTextSplitter   (langchain-text-splitters)  splitting the documentation
    OllamaEmbeddings, ChatOllama     (langchain-ollama)          embeddings, coder LLM and VLM
    Chroma                           (langchain-chroma)          the vector store on ChromaDB
Every LangChain part has a fallback: if a package is missing or a call fails, the agent
prints a note and does the same step itself (direct Ollama REST API / chromadb client).

Requirements: Python 3.9+, Ollama running, and
    pip install chromadb pypdf langchain-core langchain-ollama langchain-chroma langchain-text-splitters
(without chromadb the agent falls back to keyword search only; --no-langchain turns LangChain off).

Usage:
    python rag_agent.py "Read input.jpg, detect edges with Canny, save as edges.png"
    python rag_agent.py --model qwen2.5-coder:3b --vlm llava "..."
    python rag_agent.py --retrieve-only "how do I create a persistent chroma client"
    python rag_agent.py --answer "How do I create a persistent ChromaDB client?"
    python rag_agent.py --answer --image input.jpg "Which OpenCV function finds the squares in this image?"
    python rag_agent.py --image photo.png "Detect edges and save them as edges.png"
    python rag_agent.py --ask-image input.jpg "How many squares are on this board?"
    python rag_agent.py --rebuild "..."          # force re-indexing the documentation

WARNING: the generated code is executed on this machine (with a timeout, but not
in a sandbox).  Run the agent only in folders and on tasks you trust.
"""
