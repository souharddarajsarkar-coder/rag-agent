class LLMError(RuntimeError):
    pass


class Ollama:
    def __init__(self, host: str, timeout: int, num_ctx: int):
        self.host = host.rstrip("/")
        self.timeout, self.num_ctx = timeout, num_ctx
        # Talk to the local server directly even if an HTTP proxy is configured.
        self._opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        try:
            self.models = [m["name"] for m in self.call("/api/tags", timeout=10).get("models", [])]
        except LLMError:
            raise LLMError(SETUP_HELP.format(host=self.host)) from None
        self._caps = {}

    def call(self, path: str, payload: dict | None = None, timeout: int | None = None) -> dict:
        request = urllib.request.Request(
            self.host + path, headers={"Content-Type": "application/json"},
            data=None if payload is None else json.dumps(payload).encode("utf-8"))
        try:
            with self._opener.open(request, timeout=timeout or self.timeout) as response:
                return json.loads(response.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", "replace")[:400]
            raise LLMError(f"Ollama returned HTTP {exc.code} for {path}: {detail}") from None
        except (OSError, ValueError) as exc:
            raise LLMError(f"Cannot reach Ollama at {self.host}{path}: {exc}") from None

    def capabilities(self, model: str) -> list[str]:
        """'completion', 'vision', 'embedding' ... as reported by /api/show (newer Ollama)."""
        if model not in self._caps:
            try:
                self._caps[model] = self.call("/api/show", {"model": model}, timeout=20).get("capabilities") or []
            except LLMError:
                self._caps[model] = []
        return self._caps[model]

    def resolve(self, name: str) -> str | None:
        """Installed model matching `name` ('llava' also matches 'llava:latest')."""
        for m in self.models:
            if m == name or m == f"{name}:latest" or m.split(":")[0] == name:
                return m
        return None

    def is_embedder(self, m: str) -> bool:
        caps = self.capabilities(m)
        return "embedding" in caps or (not caps and any(h in m.lower() for h in EMBED_HINTS))

    def is_vision(self, m: str) -> bool:
        caps = self.capabilities(m)
        return "vision" in caps or (not caps and any(h in m.lower() for h in VISION_HINTS))

    def pick(self, requested: str | None, kind: str) -> str | None:
        """Choose a model of `kind` ('coder', 'vision', 'embed'); requested='none' disables it."""
        if requested and requested.lower() == "none":
            return None
        if requested and requested.lower() != "auto":
            found = self.resolve(requested)
            if not found:
                raise LLMError(f"Model '{requested}' is not installed (installed: {', '.join(self.models) or 'none'}). "
                               f"Download it with:  ollama pull {requested}")
            return found
        if kind == "embed":
            return next((m for m in self.models if self.is_embedder(m)), None)
        if kind == "vision":
            return next((m for m in self.models if self.is_vision(m)), None)
        text_models = [m for m in self.models if not self.is_embedder(m)]
        for hint in CODER_HINTS:                   # prefer code models
            for m in text_models:
                if hint in m.lower() and not self.is_vision(m):
                    return m
        return text_models[0] if text_models else None

    def chat(self, model: str, messages: list[dict], temperature: float = 0.2) -> str:
        """Chat with a model; LangChain's ChatOllama if available, else the REST API.
        A message may carry "images": [base64, ...] for vision models."""
        if "ChatOllama" in LC:
            try:
                return self._chat_langchain(model, messages, temperature)
            except Exception as exc:
                lc_failed("ChatOllama", exc)
        reply = self.call("/api/chat", {
            "model": model, "messages": messages, "stream": False,
            # num_ctx: Ollama's default context window is too small for docs + code.
            "options": {"temperature": temperature, "num_ctx": self.num_ctx},
        })["message"]["content"]
        return re.sub(r"<think>.*?</think>", "", reply or "", flags=re.DOTALL).strip()

    def _chat_langchain(self, model: str, messages: list[dict], temperature: float) -> str:
        llm = LC["ChatOllama"](model=model, temperature=temperature, num_ctx=self.num_ctx,
                               base_url=self.host)
        lc_messages = []
        for m in messages:
            if m["role"] == "system":
                lc_messages.append(LC["SystemMessage"](content=m["content"]))
            elif m["role"] == "assistant":
                lc_messages.append(LC["AIMessage"](content=m["content"]))
            elif m.get("images"):                    # image + text, as in LangChain's ChatOllama docs
                parts = [{"type": "image_url", "image_url": f"data:image/png;base64,{img}"}
                         for img in m["images"]]
                parts.append({"type": "text", "text": m["content"]})
                lc_messages.append(LC["HumanMessage"](content=parts))
            else:
                lc_messages.append(LC["HumanMessage"](content=m["content"]))
        content = llm.invoke(lc_messages).content
        if isinstance(content, list):                # some versions return content blocks
            content = "".join(p.get("text", "") if isinstance(p, dict) else str(p) for p in content)
        return re.sub(r"<think>.*?</think>", "", content or "", flags=re.DOTALL).strip()


