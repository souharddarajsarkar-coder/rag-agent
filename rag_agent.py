STOPWORDS = set("a an and are as at be by for from if in into is it its of on or that the "
                "then this to use used using with".split())


def stem(word: str) -> str:
    """Crude suffix stripping: edges/edge, blurred/blur, detection/detect ..."""
    changed = True
    while changed:
        changed = False
        for suffix in ("ing", "ion", "ed", "es", "s", "er", "or", "e"):
            if word.endswith(suffix) and len(word) - len(suffix) >= 3:
                word, changed = word[: -len(suffix)], True
                break
        if len(word) > 3 and word[-1] == word[-2]:
            word = word[:-1]
    return word


def tokenize(text: str) -> list[str]:
    """Lower-cased, stemmed tokens; identifiers are also split ('GaussianBlur' -> gaussian, blur)."""
    tokens = []
    for word in re.findall(r"[A-Za-z][A-Za-z0-9]*", text):
        parts = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+", word)
        for token in ([word] + parts) if len(parts) > 1 else [word]:
            token = stem(token.lower())
            if len(token) > 1 and token not in STOPWORDS:
                tokens.append(token)
    return tokens


class BM25:
    K1, B = 1.5, 0.75

    def __init__(self, chunks: list[Chunk]):
        self.chunks = chunks
        self.postings = defaultdict(list)
        self.lengths = []
        for i, chunk in enumerate(chunks):
            counts = Counter(tokenize(chunk.text))
            for token, tf in counts.items():
                self.postings[token].append((i, tf))
            self.lengths.append(sum(counts.values()) or 1)
        self.avg = sum(self.lengths) / max(len(chunks), 1)

    def search(self, query: str, k: int) -> list[Chunk]:
        scores = defaultdict(float)
        n = len(self.chunks)
        for token in set(tokenize(query)):
            posting = self.postings.get(token, [])
            if not posting:
                continue
            idf = math.log(1 + (n - len(posting) + 0.5) / (len(posting) + 0.5))
            for i, tf in posting:
                norm = 1 - self.B + self.B * self.lengths[i] / self.avg
                scores[i] += idf * tf * (self.K1 + 1) / (tf + self.K1 * norm)
        return [self.chunks[i] for i in sorted(scores, key=scores.get, reverse=True)[:k]]


def hash_embed(texts: list[str]) -> list[list[float]]:
    """Offline fallback embedding (no model needed): hashed bag of words + word pairs."""
    vectors = []
    for text in texts:
        vec = [0.0] * HASH_DIM
        tokens = tokenize(text)
        for feat in tokens + [a + "_" + b for a, b in zip(tokens, tokens[1:])]:
            h = int(hashlib.md5(feat.encode()).hexdigest()[:8], 16)
            vec[h % HASH_DIM] += 1.0 if (h >> 31) & 1 else -1.0
        norm = math.sqrt(sum(v * v for v in vec)) or 1.0
        vectors.append([v / norm for v in vec])
    return vectors


class Embedder:
    """Ollama embedding model (e.g. nomic-embed-text) or the offline hash fallback."""

    def __init__(self, ollama: "Ollama | None", model: str | None):
        self.ollama, self.model = ollama, model
        self.name = f"ollama:{model}" if model else "hash"
        self.lc = None                               # LangChain OllamaEmbeddings
        if model and "OllamaEmbeddings" in LC:
            try:
                self.lc = LC["OllamaEmbeddings"](model=model, base_url=ollama.host)
            except Exception as exc:
                lc_failed("OllamaEmbeddings", exc)

    def __call__(self, texts: list[str]) -> list[list[float]]:
        if not self.model:
            return hash_embed(texts)
        if self.lc is not None and "OllamaEmbeddings" in LC:
            try:
                return [list(v) for v in self.lc.embed_documents(texts)]
            except Exception as exc:
                lc_failed("OllamaEmbeddings", exc)
        vectors = []
        for i in range(0, len(texts), 32):
            batch = texts[i:i + 32]
            reply = self.ollama.call("/api/embed", {"model": self.model, "input": batch})
            vectors += reply["embeddings"]
        return vectors


def langchain_embeddings(embedder: Embedder):
    """Wrap our Embedder in LangChain's Embeddings interface (for the Chroma vector store)."""
    base = LC["Embeddings"]

    class AgentEmbeddings(base):
        def embed_documents(self, texts):
            return embedder(list(texts))

        def embed_query(self, text):
            return embedder([text])[0]

    return AgentEmbeddings()


class KnowledgeBase:
    def __init__(self, chunks: list[Chunk], collection, embedder: Embedder, store=None):
        self.chunks = chunks
        self.by_id = {c.id: c for c in chunks}
        self.collection = collection                 # raw chromadb collection
        self.store = store                           # LangChain Chroma vector store (optional)
        self.embedder = embedder
        self.bm25 = BM25(chunks)

    def vector_search(self, query: str, k: int) -> list[Chunk]:
        # Never ask ChromaDB for more results than it holds (some versions raise an error).
        k = min(k, len(self.chunks))
        if k <= 0:
            return []
        if self.store is not None and "Chroma" in LC:
            try:
                found = self.store.similarity_search(query, k=k)
                return [self.by_id[d.metadata["chunk_id"]] for d in found
                        if d.metadata.get("chunk_id") in self.by_id]
            except Exception as exc:
                lc_failed("Chroma", exc)
        if self.collection is None:
            return []
        try:
            k = min(k, self.collection.count())
            result = self.collection.query(query_embeddings=self.embedder([query]), n_results=k)
            return [self.by_id[i] for i in result["ids"][0] if i in self.by_id]
        except Exception as exc:
            print(f"      (vector search failed, using keyword search only: {exc})")
            return []

    def search(self, query: str, k: int, skip=frozenset()) -> list[Chunk]:
        """Hybrid search: reciprocal-rank fusion of ChromaDB and BM25 results.  Chunks in
        `skip` (already shown) are left out - unless nothing else is relevant."""
        scores = defaultdict(float)
        for ranking in (self.vector_search(query, 3 * k + len(skip)), self.bm25.search(query, 3 * k + len(skip))):
            for rank, chunk in enumerate(ranking):
                scores[chunk.id] += 1.0 / (60 + rank)
        ranked = sorted(scores, key=scores.get, reverse=True)
        best = [i for i in ranked if i not in skip] or ranked   # small docs folder: allow repeats
        return [self.by_id[i] for i in best[:k]]


def open_chroma(db_dir: Path):
    import chromadb
    try:
        from chromadb.config import Settings
        return chromadb.PersistentClient(path=str(db_dir), settings=Settings(anonymized_telemetry=False))
    except Exception:
        return chromadb.PersistentClient(path=str(db_dir))


def build_knowledge_base(docs_dir: Path, embedder: Embedder, rebuild: bool) -> KnowledgeBase:
    files = doc_files(docs_dir)
    if not files:
        raise SystemExit(f"No documentation files found in '{docs_dir}'. "
                         f"Put the PDFs / HTML / text files there or pass --docs-dir.")
    db_dir = Path(DB_DIR)
    info_file, chunks_file = db_dir / "index_info.json", db_dir / "chunks.json"
    chunks_fp = folder_fingerprint(files)                       # depends on the files only
    vectors_fp = hashlib.sha1(f"{chunks_fp}|{embedder.name}".encode()).hexdigest()
    info = {}
    if not rebuild:
        try:
            info = json.loads(info_file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            info = {}

    # ---- the chunks (cached in chunks.json, also without chromadb) ------------
    chunks = None
    if info.get("chunks_fingerprint") == chunks_fp:
        try:
            chunks = [Chunk(**c) for c in json.loads(chunks_file.read_text(encoding="utf-8"))]
            print(f"      Re-using the {len(chunks)} chunks of {len(files)} unchanged file(s)")
        except (OSError, ValueError, TypeError):
            chunks = None                                       # cache missing / damaged
    if chunks is None:
        print(f"      Reading {len(files)} documentation file(s) from {docs_dir}")
        chunks = load_chunks(docs_dir, files)
        db_dir.mkdir(exist_ok=True)
        chunks_file.write_text(json.dumps([c.__dict__ for c in chunks]), encoding="utf-8")
        info = {"chunks_fingerprint": chunks_fp}
    if not chunks:
        raise SystemExit(f"The documentation files in '{docs_dir}' contain no readable text.")

    # ---- the vectors (ChromaDB, through LangChain's Chroma if available) ------
    collection, store = None, None
    vectors_ok = info.get("vectors_fingerprint") == vectors_fp
    try:
        client = open_chroma(db_dir)
        collection = client.get_or_create_collection(name=COLLECTION, embedding_function=None)
        if not vectors_ok or collection.count() != len(chunks):  # changed or incomplete: rebuild
            try:
                client.delete_collection(COLLECTION)
            except Exception:
                pass                                       # nothing to delete yet
            collection = client.get_or_create_collection(name=COLLECTION, embedding_function=None)
            vectors_ok = False
        if "Chroma" in LC:                         # LangChain vector store on the same client
            try:
                store = LC["Chroma"](client=client, collection_name=COLLECTION,
                                     embedding_function=langchain_embeddings(embedder))
            except Exception as exc:
                lc_failed("Chroma", exc)
        if not vectors_ok:
            print(f"      Embedding {len(chunks)} chunks into ChromaDB with '{embedder.name}'"
                  f"{' via LangChain Chroma' if store is not None else ''} ...")
            started, batch = time.time(), 64
            for i in range(0, len(chunks), batch):
                part = chunks[i:i + batch]
                metadatas = [{"source": c.source, "page": c.page, "chunk_id": c.id} for c in part]
                added = False
                if store is not None and "Chroma" in LC:
                    try:
                        docs = [LC["Document"](page_content=c.text, metadata=m) for c, m in zip(part, metadatas)]
                        store.add_documents(documents=docs, ids=[c.id for c in part])
                        added = True
                    except Exception as exc:
                        lc_failed("Chroma", exc)
                        store = None
                if not added:
                    collection.add(ids=[c.id for c in part], documents=[c.text for c in part],
                                   embeddings=embedder([c.text for c in part]), metadatas=metadatas)
                print(f"\r      {min(i + batch, len(chunks))}/{len(chunks)} chunks stored", end="", flush=True)
            print(f"  ({time.time() - started:.0f}s)")
            collection = client.get_or_create_collection(name=COLLECTION, embedding_function=None)
            info["vectors_fingerprint"] = vectors_fp
        print(f"      ChromaDB collection '{COLLECTION}' in ./{DB_DIR}: {collection.count()} vectors"
              f"{'  (searched through LangChain Chroma)' if store is not None else ''}")
    except ImportError:
        print("      (chromadb is not installed -> keyword search only.  pip install chromadb)")
        collection, store = None, None
    except Exception as exc:
        print(f"      (ChromaDB unavailable -> keyword search only: {exc})")
        collection, store = None, None
    if collection is None:
        info.pop("vectors_fingerprint", None)
    info["embedder"] = embedder.name
    db_dir.mkdir(exist_ok=True)
    info_file.write_text(json.dumps(info), encoding="utf-8")
    return KnowledgeBase(chunks, collection, embedder, store)


def format_docs(chunks: list[Chunk]) -> str:
    if not chunks:
        return "(nothing relevant found)"
    return "\n\n".join(f"[{i}] {c.label()}\n{c.snippet()}" for i, c in enumerate(chunks, 1))


