def image_info(path: Path):
    """(base64 image for the VLM, width, height, pixel std-dev) - the image is shrunk to <= 1024 px."""
    try:
        import cv2
        img = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
        if img is not None:
            h, w = img.shape[:2]
            std = float(img.std())
            scale = 1024 / max(h, w)
            if scale < 1:
                img = cv2.resize(img, (int(w * scale), int(h * scale)), interpolation=cv2.INTER_AREA)
            if img.dtype != "uint8":
                img = cv2.normalize(img, None, 0, 255, cv2.NORM_MINMAX).astype("uint8")
            ok, buf = cv2.imencode(".png", img)
            if ok:
                return base64.b64encode(buf.tobytes()).decode(), w, h, std
    except ImportError:
        pass
    return base64.b64encode(path.read_bytes()).decode(), "?", "?", None


def ask_vlm(ollama: Ollama, vlm: str, image: Path, prompt: str) -> str:
    b64, *_ = image_info(image)
    return ollama.chat(vlm, [{"role": "user", "content": prompt, "images": [b64]}], temperature=0.1)


def images_in(folder: Path) -> dict[str, tuple]:
    """Image files directly in `folder` -> (size, mtime), to see which ones a script wrote."""
    return {p.name: (p.stat().st_size, p.stat().st_mtime) for p in folder.iterdir()
            if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS}


PRODUCED_FILE = "produced_images.json"     # in --out-dir: images written by earlier runs
OUTPUT_WORDS = re.compile(r"(save|saved|saving|write|writes|written|store|output|export|result|produce)\w*"
                          r"(\s+\w+){0,4}\s*(as|to|into|in|named|called|file)?\s*['\"]?$", re.I)


def produced_images(out_dir: Path) -> set[str]:
    try:
        return set(json.loads((out_dir / PRODUCED_FILE).read_text(encoding="utf-8")))
    except (OSError, ValueError):
        return set()


def remember_outputs(out_dir: Path, names: list[str]) -> None:
    done = produced_images(out_dir) | set(names)
    (out_dir / PRODUCED_FILE).write_text(json.dumps(sorted(done)), encoding="utf-8")


def mentioned_images(task: str, names) -> tuple[list[str], list[str]]:
    """Split the image files named in the task into (inputs, outputs).  A name counts as an
    output when the words just before it say so: 'save as X', 'write the result to X' ..."""
    inputs, outputs = [], []
    for name in names:
        for match in re.finditer(re.escape(name), task, re.I):
            before = task[max(0, match.start() - 45):match.start()]
            (outputs if OUTPUT_WORDS.search(before) else inputs).append(name)
            break
    return inputs, outputs


def input_images(task: str, workdir: Path, out_dir: Path, explicit: list[str] | None = None,
                 limit: int = 2) -> list[Path]:
    """The input image(s) of the task:
    1. images given with --image;  2. images the task names as inputs ('Read input.jpg');
    3. otherwise the images in the folder that are not outputs of this task or of earlier
       runs - one of them, preferring a name containing 'input'."""
    if explicit:
        return [Path(p) if Path(p).is_absolute() else workdir / p for p in explicit][:limit]
    present = sorted(images_in(workdir))
    named_in, named_out = mentioned_images(task, present)
    if named_in:
        return [workdir / n for n in named_in][:limit]
    # names in the task that do not exist yet are outputs too
    task_names = set(re.findall(r"[\w\-.]+\.(?:png|jpe?g|bmp|tiff?|webp)", task, re.I))
    excluded = set(named_out) | task_names | produced_images(out_dir)
    candidates = [n for n in present if n not in excluded]
    if not candidates:
        return []
    preferred = [n for n in candidates if "input" in n.lower()] or candidates
    if len(preferred) > 1 and preferred is candidates:
        print(f"      (several possible input images: {', '.join(candidates)}; "
              f"using {preferred[0]} - choose another one with --image NAME)")
    return [workdir / preferred[0]]


def describe_inputs(ollama: Ollama, vlm: str, task: str, images: list[Path]) -> str:
    notes = []
    for img in images:
        _, w, h, _ = image_info(img)
        started = time.time()
        text = ask_vlm(ollama, vlm, img, DESCRIBE_PROMPT.format(w=w, h=h, name=img.name, task=task))
        print(f"      {img.name} ({w}x{h}) described in {time.time() - started:.1f}s: "
              f"{' '.join(text.split())[:160]}...")
        notes.append(f"- {img.name} ({w}x{h} pixels): {' '.join(text.split())[:800]}")
    return "\n# WHAT THE INPUT IMAGES SHOW (seen by a vision model)\n" + "\n".join(notes) + "\n" if notes else ""


def verify_outputs(ollama: Ollama, vlm: str | None, task: str, outputs: list[Path]) -> tuple[bool, str]:
    """Check the images a successful script wrote.  Returns (looks_ok, report)."""
    reports, ok = [], True
    for img in outputs[:3]:
        _, w, h, std = image_info(img)
        if std is not None and std < 1e-6:          # every pixel identical: certainly wrong
            ok = False
            reports.append(f"- {img.name}: the image is completely uniform (all pixels have the same value), "
                           "so it contains no result. Check the parameters / the input that was processed.")
            continue
        if vlm:
            answer = ask_vlm(ollama, vlm, img, VERIFY_PROMPT.format(task=task, name=img.name, w=w, h=h))
            verdict_no = re.search(r"VERDICT\s*:\s*NO", answer, re.I) is not None
            reason = " ".join(re.sub(r"VERDICT\s*:\s*(YES|NO)", "", answer, flags=re.I).split())[:300]
            print(f"      VLM check of {img.name}: {'NO' if verdict_no else 'YES'} - {reason[:160]}")
            if verdict_no:
                ok = False
                reports.append(f"- {img.name}: a vision model looked at it and judged it WRONG: {reason}")
    return ok, "\n".join(reports)


