def parse_args(argv=None):
    p = argparse.ArgumentParser(description="Offline RAG + VLM agent that writes, runs and "
                                            "self-corrects Computer Vision code.")
    p.add_argument("task", nargs="*", help="natural-language description of the CV task")
    p.add_argument("--task-file", help="read the task description from this text file")
    p.add_argument("--model", default="auto", help="coder model in Ollama (default: auto, prefers *coder*)")
    p.add_argument("--vlm", default="auto", help="vision model, e.g. llava (default: auto-detect; 'none' = off)")
    p.add_argument("--embed-model", default="auto",
                   help="Ollama embedding model, e.g. nomic-embed-text (default: auto; 'none' = offline hash embedding)")
    p.add_argument("--docs-dir", default=DEFAULT_DOCS_DIR, help=f"documentation folder (default: {DEFAULT_DOCS_DIR})")
    p.add_argument("--rebuild", action="store_true", help="re-index the documentation into ChromaDB")
    p.add_argument("--host", default=DEFAULT_HOST, help=f"Ollama address (default: {DEFAULT_HOST})")
    p.add_argument("--max-attempts", type=int, default=5, help="generate/repair rounds (default: 5)")
    p.add_argument("--vlm-retries", type=int, default=1,
                   help="how many times a wrong-looking output is sent back for correction (default: 1; 0 = no check)")
    p.add_argument("--no-describe", action="store_true", help="do not describe the input image with the VLM")
    p.add_argument("--timeout", type=int, default=60, help="seconds a generated script may run (default: 60)")
    p.add_argument("--top-k", type=int, default=6, help="documentation chunks given to the coder (default: 6)")
    p.add_argument("--workdir", default=".", help="folder the generated script runs in (default: current)")
    p.add_argument("--out-dir", default="agent_output", help="where attempts, solution.py and the log go")
    p.add_argument("--temperature", type=float, default=0.2, help="temperature of the first attempt")
    p.add_argument("--num-ctx", type=int, default=8192, help="context window requested from Ollama (tokens)")
    p.add_argument("--llm-timeout", type=int, default=900, help="seconds to wait for one model reply")
    p.add_argument("--retrieve-only", action="store_true", help="only show the retrieved documentation")
    p.add_argument("--answer", action="store_true",
                   help="answer a text question from the documentation instead of writing code")
    p.add_argument("--image", action="append", metavar="IMAGE",
                   help="input image for the task / question (repeatable); default: auto-detect")
    p.add_argument("--ask-image", metavar="IMAGE", help="only ask the vision model a question about IMAGE")
    p.add_argument("--no-langchain", action="store_true", help="do not use LangChain (built-in code only)")
    p.add_argument("--verbose", action="store_true", help="print retrieved documentation and generated code")
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    args.max_attempts = max(1, args.max_attempts)
    if args.task_file:
        task = Path(args.task_file).read_text(encoding="utf-8").strip()
    else:
        task = " ".join(args.task).strip() or input("Describe the Computer Vision task: ").strip()
    if not task:
        print("No task given.")
        return 2
    print(f"TASK: {task}")

    if not args.no_langchain:
        LC.update(load_langchain())
    wanted = ["RecursiveCharacterTextSplitter", "OllamaEmbeddings", "Chroma", "ChatOllama"]
    if LC:
        used = [w for w in wanted if w in LC]
        print(f"LangChain: {', '.join(used) or 'only langchain-core'}"
              + ("" if len(used) == len(wanted) else
                 f"   (missing: {', '.join(w for w in wanted if w not in LC)} -> built-in fallback)"))
    else:
        print("LangChain: " + ("off (--no-langchain)" if args.no_langchain else
              "not installed -> built-in fallback  (pip install langchain-core langchain-ollama "
              "langchain-chroma langchain-text-splitters)"))

    try:
        ollama = Ollama(args.host, args.llm_timeout, args.num_ctx)
    except LLMError as exc:
        if not args.retrieve_only or args.embed_model not in ("auto", "none"):
            print(f"\nLLM error: {exc}")
            return 2
        ollama = None                               # retrieval with hash embeddings still works

    try:
        # ---- only ask the vision model about an image -------------------------
        if args.ask_image:
            vlm = ollama.pick(args.vlm if args.vlm != "none" else "auto", "vision")
            if not vlm:
                print("No vision model installed. Download one, e.g.:  ollama pull llava")
                return 2
            print(f"Vision model: {vlm}\n")
            print(ask_vlm(ollama, vlm, Path(args.ask_image), task))
            return 0

        embed_model = ollama.pick(args.embed_model, "embed") if ollama else None
        embedder = Embedder(ollama, embed_model)
        print("\n[1/5] Loading the documentation knowledge base (ChromaDB)")
        print(f"      Embeddings: {embedder.name}"
              + ("" if embed_model else "  (no embedding model found; e.g.  ollama pull nomic-embed-text)"))
        kb = build_knowledge_base(find_docs_dir(args.docs_dir), embedder, args.rebuild)

        if args.retrieve_only:
            print("\n" + format_docs(kb.search(task, args.top_k)))
            return 0

        coder = ollama.pick(args.model, "coder")
        if not coder:
            print("No chat model installed. Download one:  ollama pull qwen2.5-coder:3b")
            return 2
        vlm = ollama.pick(args.vlm, "vision")
        if vlm == coder:
            vlm = None
        print(f"      Coder LLM   : {coder}")
        print(f"      Vision model: {vlm or 'none  (optional: ollama pull llava)'}")
        if args.answer:
            return answer_question(task, kb, ollama, coder, vlm, args)
        return 0 if run_agent(task, kb, ollama, coder, vlm, args) else 1
    except LLMError as exc:
        print(f"\nLLM error: {exc}")
        return 2


if __name__ == "__main__":
    sys.exit(main())
