def run_agent(task: str, kb: KnowledgeBase, ollama: Ollama, coder: str, vlm: str | None, args) -> bool:
    workdir = Path(args.workdir).resolve()
    out_dir = Path(args.out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    files = sorted(p.name for p in workdir.iterdir()
                   if p.is_file() and p.suffix.lower() in INPUT_EXTENSIONS)[:40]
    versions = library_versions()
    log = {"task": task, "coder": coder, "vlm": vlm, "embedder": kb.embedder.name,
           "langchain": sorted(k for k in LC if k[0].isupper() and k not in
                               ("Document", "Embeddings", "AIMessage", "HumanMessage", "SystemMessage")),
           "libraries": versions, "attempts": []}

    # ---- LOOK: the vision model describes the input image(s) ---------------
    vision = ""
    imgs = [p for p in input_images(task, workdir, out_dir, args.image) if p.exists()]
    log["input_images"] = [p.name for p in imgs]
    if vlm and not args.no_describe:
        if imgs:
            print(f"\n[2/5] Looking at the input image(s) with the vision model {vlm}")
            try:
                vision = describe_inputs(ollama, vlm, task, imgs)
            except LLMError as exc:
                print(f"      (vision model failed, continuing without it: {exc})")
            log["image_description"] = vision.strip()
    if not vision:
        print("\n[2/5] No input image description (no vision model or no input image)")

    # ---- RETRIEVE ------------------------------------------------------------
    print("\n[3/5] Retrieving documentation for the task")
    plan = ollama.chat(coder, [{"role": "user", "content": PLAN_PROMPT.format(versions=versions, task=task)}], 0.0)
    api_names = list(dict.fromkeys(re.findall(r"[A-Za-z_][\w]*\.[\w.]*\w", plan)))[:10]
    docs = kb.search(task + " " + " ".join(api_names), args.top_k)
    print(f"      APIs suggested by the coder : {', '.join(api_names) or '(none)'}")
    print(f"      Documentation retrieved     : {', '.join(c.label() for c in docs)}")
    if args.verbose:
        print(format_docs(docs))
    log.update(suggested_apis=api_names, retrieved=[c.label() for c in docs])

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT.format(versions=versions)},
        {"role": "user", "content": TASK_PROMPT.format(
            task=task, vision=vision, docs=format_docs(docs),
            files=(", ".join(files) or "(no data files)")
                  + (f"\nThe input image for this task is: {', '.join(p.name for p in imgs)}" if imgs else ""))},
    ]
    shown = frozenset(c.id for c in docs)
    earlier_errors: list[str] = []
    best_script, rejections, success, attempt, result = None, 0, False, 0, None

    # ---- GENERATE -> EXECUTE -> CORRECT -> VERIFY -----------------------------
    print("\n[4/5] Generating, running and correcting code")
    for attempt in range(1, args.max_attempts + 1):
        temperature = min(args.temperature + 0.15 * (attempt - 1), 0.9)
        started = time.time()
        reply = ollama.chat(coder, messages, temperature)
        code = extract_code(reply)
        script = out_dir / f"attempt_{attempt}.py"
        script.write_text(code, encoding="utf-8")
        print(f"  Attempt {attempt}/{args.max_attempts}: code generated in {time.time() - started:.1f}s"
              f" -> {script.name} ({len(code.splitlines())} lines)")
        fix_note = re.search(r"^\W*FIX:\s*(.+)$", reply, re.MULTILINE)
        if fix_note:
            print(f"      Coder's diagnosis: {fix_note.group(1).strip()[:200]}")
        if args.verbose:
            print(code)

        result, error_docs, hints = None, [], []
        gui_call = GUI_CALL.search(code_only(code))
        if not code:
            failure = "Your reply did not contain a Python code block, so nothing could be executed."
        elif gui_call:
            failure = (f"NOT EXECUTED: the script calls `{gui_call.group(0)}...)`, which needs a display or "
                       "keyboard, but it runs headless. Remove every GUI / interactive call and save "
                       "results to files instead.")
        else:
            before = images_in(workdir)
            result = run_script(script, workdir, args.timeout)
            failure = find_failure(result, args.timeout)
            if failure:
                failure = failure.replace(str(script.parent) + os.sep, "")
            else:
                print(f"      Executed successfully in {result.seconds:.1f}s (exit code 0)")
                best_script = script
                after = images_in(workdir)
                outputs = [workdir / n for n, stamp in after.items() if before.get(n) != stamp]
                remember_outputs(out_dir, [o.name for o in outputs if o not in imgs])
                looks_ok, report = True, ""
                if outputs and rejections < args.vlm_retries:
                    print(f"[5/5] Checking the output image(s): {', '.join(o.name for o in outputs)}")
                    try:
                        looks_ok, report = verify_outputs(ollama, vlm, task, outputs)
                    except LLMError as exc:
                        print(f"      (vision check failed, accepting the result: {exc})")
                entry = {"attempt": attempt, "script": str(script), "ran": True,
                         "outputs": [o.name for o in outputs], "check": report or "ok"}
                log["attempts"].append(entry)
                if looks_ok:
                    success = True
                    break
                rejections += 1
                failure = ("The script ran without errors, but its OUTPUT IS WRONG:\n" + report +
                           f"\n--- stdout ---\n{tail(result.stdout, 600)}")
                print(f"      OUTPUT REJECTED: {report.splitlines()[0][:200]}")
                result = None                       # no traceback to analyse

        if result is not None or not log["attempts"] or log["attempts"][-1].get("attempt") != attempt:
            log["attempts"].append({"attempt": attempt, "script": str(script), "ran": result is not None})
        entry = log["attempts"][-1]
        summary = exception_line(failure) or failure.splitlines()[0]
        if result is not None:                      # crashed: docs for the failing API
            names, hints = analyse_error(failure, files)
            if names:
                error_docs = kb.search(" ".join(names) + " " + exception_line(failure), ERROR_TOP_K, skip=shown)
            print(f"      FAILED: {summary[:230]}")
            print(f"      Documentation retrieved for the error: "
                  f"{', '.join(c.label() for c in error_docs) or '(none)'}")
        elif "OUTPUT IS WRONG" not in failure:
            print(f"      FAILED: {summary[:230]}")
        entry.update(error=failure, error_docs=[c.label() for c in error_docs], hints=hints)

        feedback = ["Your script FAILED.", "", "# PROBLEM", failure]
        if hints:
            feedback += ["", "# HINTS", *hints]
        if error_docs:
            feedback += ["", "# DOCUMENTATION RELATED TO THE ERROR", format_docs(error_docs)]
        if earlier_errors:
            feedback += ["", "# EARLIER ATTEMPTS FAILED WITH (do not reintroduce these errors)",
                         *(f"- {e}" for e in earlier_errors[-3:])]
        feedback += ["", "First write one line starting with 'FIX:' that names the root cause. "
                         "Then reply with the complete corrected script in a single ```python block."]
        earlier_errors.append(summary[:300])
        messages = messages[:2] + [{"role": "assistant", "content": f"```python\n{code}```"},
                                   {"role": "user", "content": "\n".join(feedback)}]

    # ---- Result -------------------------------------------------------------
    print("\n[Result]")
    if not success and best_script is not None:     # an earlier version ran: keep that one
        print(f"  The output check was not passed, but {best_script.name} runs without errors;"
              f" re-running it and keeping it as the solution.")
        result = run_script(best_script, workdir, args.timeout)
        script, success = best_script, find_failure(result, args.timeout) is None
    log["success"] = success
    if success:
        solution = out_dir / "solution.py"
        shutil.copyfile(script, solution)
        log["solution"] = str(solution)
        print(f"  SUCCESS after {attempt} attempt(s). Working script: {solution}")
        print("  ----- output of the script -----")
        print("  " + (tail(result.stdout) or "(no output)").replace("\n", "\n  "))
    else:
        print(f"  FAILED: no working script after {args.max_attempts} attempts. "
              f"Last error: {earlier_errors[-1][:230] if earlier_errors else '?'}")
    (out_dir / "run_log.json").write_text(json.dumps(log, indent=2), encoding="utf-8")
    print(f"  Attempts and log saved in: {out_dir}")
    return success


def answer_question(question: str, kb: KnowledgeBase, ollama: Ollama, model: str,
                    vlm: str | None, args) -> int:
    """--answer mode: the LLM answers a text question from the documentation (RAG),
    optionally with a vision model's description of an image (--image or named in the question)."""
    workdir = Path(args.workdir).resolve()
    out_dir = Path(args.out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    vision, imgs = "", []
    if args.image:
        imgs = input_images(question, workdir, out_dir, args.image)
    else:                                       # only images the question names as inputs
        named, _ = mentioned_images(question, sorted(images_in(workdir)))
        imgs = [workdir / n for n in named[:2]]
    imgs = [p for p in imgs if p.exists()]
    if imgs and vlm:
        print(f"\n[2/3] Looking at {', '.join(p.name for p in imgs)} with the vision model {vlm}")
        try:
            vision = describe_inputs(ollama, vlm, question, imgs)
        except LLMError as exc:
            print(f"      (vision model failed, continuing without it: {exc})")
    elif imgs:
        print("\n[2/3] (an image was given, but no vision model is installed:  ollama pull llava)")

    print("\n[3/3] Retrieving documentation and asking", model)
    docs = kb.search(question, args.top_k)
    print(f"      Documentation retrieved: {', '.join(c.label() for c in docs)}")
    if args.verbose:
        print(format_docs(docs))
    started = time.time()
    answer = ollama.chat(model, [
        {"role": "system", "content": ANSWER_SYSTEM},
        {"role": "user", "content": ANSWER_PROMPT.format(question=question, vision=vision, docs=format_docs(docs))},
    ], temperature=0.2)
    print(f"      answered in {time.time() - started:.1f}s")

    sources = "\n".join(f"[{i}] {c.label()}" for i, c in enumerate(docs, 1))
    print("\n" + "=" * 70 + "\nANSWER\n" + "=" * 70)
    print(answer)
    print("\nSources:\n" + sources)
    report = (f"# Question\n\n{question}\n\n# Answer ({model})\n\n{answer}\n\n# Sources\n\n{sources}\n"
              + (f"\n# Image description ({vlm})\n{vision}" if vision else ""))
    (out_dir / "answer.md").write_text(report, encoding="utf-8")
    print(f"\n(saved to {out_dir / 'answer.md'})")
    return 0


