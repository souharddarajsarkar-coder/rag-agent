@dataclass
class Chunk:
    id: str
    source: str      # file name relative to the documentation folder
    page: int        # PDF page (0 for other files)
    text: str

    def label(self) -> str:
        return f"{self.source}" + (f" p.{self.page}" if self.page else "")

    def snippet(self, limit: int = MAX_DOC_CHARS) -> str:
        if len(self.text) <= limit:
            return self.text
        cut = self.text.rfind(" ", 0, limit)
        return self.text[: cut if cut > limit // 2 else limit].rstrip() + " ..."


class _HTMLText(HTMLParser):
    """Collect the visible text of an HTML page (standard library only)."""
    BLOCK = {"p", "div", "br", "li", "tr", "h1", "h2", "h3", "h4", "h5", "h6", "pre", "dt", "dd", "section"}
    HIDDEN = {"script", "style", "nav", "header", "footer"}

    def __init__(self):
        super().__init__()
        self.parts, self._skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in self.HIDDEN:
            self._skip += 1
        elif tag in self.BLOCK:
            self.parts.append("\n\n")

    def handle_endtag(self, tag):
        if tag in self.HIDDEN and self._skip:
            self._skip -= 1
        elif tag in self.BLOCK:
            self.parts.append("\n\n")

    def handle_data(self, data):
        if not self._skip:
            self.parts.append(data)


def find_docs_dir(requested: str) -> Path:
    """The documentation folder; matched case-insensitively ('documentation', 'docs' ...)."""
    path = Path(requested)
    if path.is_dir():
        return path
    for candidate in Path(".").iterdir():
        if candidate.is_dir() and candidate.name.lower() in {requested.lower(), "documentation", "docs"}:
            return candidate
    return path


def doc_files(folder: Path) -> list[Path]:
    """Documentation files in the folder, skipping hidden / system files such as .DS_Store."""
    files = []
    for path in sorted(folder.rglob("*")):
        parts = path.relative_to(folder).parts
        if any(p.startswith(".") or p in ("__MACOSX", "__pycache__") for p in parts):
            continue                               # .DS_Store, ._file, .git ...
        if path.is_file() and path.suffix.lower() in DOC_EXTENSIONS:
            files.append(path)
    return files


def read_pdf_pages(path: Path) -> list[str]:
    try:
        try:
            from pypdf import PdfReader
        except ImportError:
            from PyPDF2 import PdfReader
        return [page.extract_text() or "" for page in PdfReader(str(path)).pages]
    except ImportError:
        pass
    except Exception as exc:
        print(f"      (pypdf could not read {path.name}: {exc})")
    if shutil.which("pdftotext"):                  # poppler-utils fallback
        out = subprocess.run(["pdftotext", "-layout", str(path), "-"], capture_output=True,
                             text=True, errors="replace")
        return out.stdout.split("\f")
    print(f"      (skipping {path.name}: run  pip install pypdf  to read PDF files)")
    return []


def remove_repeated_lines(pages: list[str]) -> list[str]:
    """Drop running headers / footers ('Page 3 / 83', the document title on every page)."""
    if len(pages) < 4:
        return pages
    counts = Counter(line.strip() for page in pages for line in set(page.splitlines()) if line.strip())
    repeated = {line for line, n in counts.items() if n > 0.5 * len(pages) and len(line) < 80}
    cleaned = []
    for page in pages:
        lines = [l for l in page.splitlines()
                 if l.strip() not in repeated and not re.fullmatch(r"\s*Page \d+\s*(/|of)\s*\d+\s*", l)]
        cleaned.append("\n".join(lines))
    return cleaned


def read_doc_pages(path: Path) -> list[str]:
    """Text of a documentation file, one string per page."""
    suffix = path.suffix.lower()
    if suffix == ".pdf":
        return remove_repeated_lines(read_pdf_pages(path))
    text = path.read_text(encoding="utf-8", errors="replace")
    if suffix in (".html", ".htm"):
        parser = _HTMLText()
        parser.feed(text)
        text = re.sub(r"[ \t]+", " ", "".join(parser.parts))
    elif suffix == ".ipynb":
        try:
            cells = json.loads(text).get("cells", [])
            text = "\n\n".join("".join(c.get("source", [])) for c in cells)
        except ValueError:
            pass
    return [text]


def split_text(text: str, size: int = CHUNK_CHARS) -> list[str]:
    """Cut text into chunks of about `size` characters (LangChain's splitter if available)."""
    if "RecursiveCharacterTextSplitter" in LC:
        try:
            splitter = LC["RecursiveCharacterTextSplitter"](chunk_size=size, chunk_overlap=150)
            return [c.strip() for c in splitter.split_text(text) if c.strip()]
        except Exception as exc:
            lc_failed("RecursiveCharacterTextSplitter", exc)
    pieces = []
    for paragraph in re.split(r"\n\s*\n", text):
        paragraph = paragraph.strip("\n")
        if not paragraph.strip():
            continue
        while len(paragraph) > size:               # very long paragraph: cut at a line break
            cut = paragraph.rfind("\n", 0, size)
            cut = cut if cut > size // 3 else size
            pieces.append(paragraph[:cut])
            paragraph = paragraph[cut:].lstrip("\n")
        pieces.append(paragraph)
    chunks, chunk = [], ""
    for piece in pieces:
        if chunk and len(chunk) + len(piece) > size:
            chunks.append(chunk.strip())
            chunk = ""
        chunk += piece + "\n\n"
    if chunk.strip():
        chunks.append(chunk.strip())
    return chunks


def load_chunks(folder: Path, files: list[Path]) -> list[Chunk]:
    chunks = []
    for path in files:
        rel = str(path.relative_to(folder))
        pages = read_doc_pages(path)
        before = len(chunks)
        for page_no, page in enumerate(pages, 1):
            for i, text in enumerate(split_text(page)):
                if len(text) > 40:
                    chunks.append(Chunk(f"{rel}::{page_no}::{i}", rel,
                                        page_no if len(pages) > 1 else 0, text))
        print(f"      {rel}: {len(pages)} page(s) -> {len(chunks) - before} chunks")
    return chunks


def folder_fingerprint(files: list[Path]) -> str:
    """Changes when a documentation file, the chunk size or the splitter changes."""
    splitter = "lc" if "RecursiveCharacterTextSplitter" in LC else "own"
    h = hashlib.sha1(f"{CHUNK_CHARS}|{splitter}".encode())
    for f in files:
        st = f.stat()
        h.update(f"{f}|{st.st_size}|{int(st.st_mtime)}".encode())
    return h.hexdigest()


